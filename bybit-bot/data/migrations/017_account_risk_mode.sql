-- v0.9.1: Режим риска (risk_mode) для каждого аккаунта.
--
-- Определяет формулу расчёта movement_coef в §6.3 (trailing stop):
--
--   conservative — формула 2^k: наименьшее k ≥ 0 такое, что 2^k ≥ p (p < 2 → k=1).
--                  Даёт более жёсткий (близкий) триггер и более тугой трейл.
--                  Исторический режим работы бота до v0.9.1.
--
--   standard     — формула floor(p/4)+1.
--                  Шкала «по четвёркам»: p∈[0,4)→1, [4,8)→2, [8,12)→3 ...
--                  Даёт более широкий триггер и мягкий трейл — меньше преждевременных закрытий.
--
-- Дефолт = 'conservative' для обратной совместимости со всеми существующими аккаунтами.

ALTER TABLE bybit_accounts ADD COLUMN risk_mode TEXT NOT NULL DEFAULT 'conservative';
